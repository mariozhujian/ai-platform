-- 与当前配置一致：1024 维、COSINE_DISTANCE、HNSW。
-- 如向量表已存在，则保留原表。
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS vector_store (
                                            id UUID PRIMARY KEY,
                                            content TEXT,
                                            metadata JSON,
                                            embedding VECTOR(1024)
    );

COMMENT ON TABLE vector_store IS '知识库文档向量存储';
COMMENT ON COLUMN vector_store.id IS '文档片段唯一标识';
COMMENT ON COLUMN vector_store.content IS '文档片段文本内容';
COMMENT ON COLUMN vector_store.metadata IS '文档片段元数据，包含知识库编号、文件哈希等信息';
COMMENT ON COLUMN vector_store.embedding IS '文档片段的向量表示，维度为1024';

CREATE INDEX IF NOT EXISTS idx_vector_store_embedding_hnsw
    ON vector_store USING hnsw (embedding vector_cosine_ops);

-- 给旧向量补充知识库归属；使用字符串，和 Java 写入保持一致。
UPDATE vector_store
SET metadata = (
    COALESCE(metadata::jsonb, '{}'::jsonb)
        || jsonb_build_object('knowledge_base_id', '1')
    )::json
WHERE metadata ->> 'knowledge_base_id' IS NULL;

CREATE INDEX IF NOT EXISTS idx_vector_store_knowledge_base
    ON vector_store ((metadata ->> 'knowledge_base_id'));
