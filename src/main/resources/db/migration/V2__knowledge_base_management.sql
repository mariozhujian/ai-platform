CREATE TABLE knowledge_base (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                name VARCHAR(100) NOT NULL CHECK (btrim(name) <> ''),
                                description VARCHAR(2000) NOT NULL DEFAULT '',
                                owner_id VARCHAR(100) NOT NULL CHECK (btrim(owner_id) <> ''),
                                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE knowledge_base IS '知识库';
COMMENT ON COLUMN knowledge_base.id IS '知识库主键，自增编号';
COMMENT ON COLUMN knowledge_base.name IS '知识库名称';
COMMENT ON COLUMN knowledge_base.description IS '知识库描述';
COMMENT ON COLUMN knowledge_base.owner_id IS '知识库所有者标识';
COMMENT ON COLUMN knowledge_base.created_at IS '知识库创建时间';
COMMENT ON COLUMN knowledge_base.updated_at IS '知识库更新时间';

