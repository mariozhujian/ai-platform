CREATE TABLE ai_app (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(100) NOT NULL CHECK (btrim(name) <> ''),
                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_knowledge_base (
                                    app_id BIGINT NOT NULL REFERENCES ai_app(id) ON DELETE CASCADE,
                                    knowledge_base_id BIGINT NOT NULL REFERENCES knowledge_base(id),
                                    PRIMARY KEY (app_id, knowledge_base_id)
);

COMMENT ON TABLE ai_app IS '人工智能应用';
COMMENT ON COLUMN ai_app.id IS '应用主键，自增编号';
COMMENT ON COLUMN ai_app.name IS '应用名称';
COMMENT ON COLUMN ai_app.created_at IS '应用创建时间';

COMMENT ON TABLE app_knowledge_base IS '应用与知识库关联关系';
COMMENT ON COLUMN app_knowledge_base.app_id IS '应用编号，关联人工智能应用';
COMMENT ON COLUMN app_knowledge_base.knowledge_base_id IS '知识库编号，关联知识库';

CREATE INDEX idx_app_knowledge_base_kb
    ON app_knowledge_base (knowledge_base_id);

